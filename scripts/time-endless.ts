// Measuring tool: npx tsx scripts/time-endless.ts [jobs=3] [results.json]
// Times makeEndless for every cube size cols ≤ rows (2-6) × maxH 1-6 on seeds 1..7, each seed in its own child
// process killed after 30 s. A size stops early once 4 seeds hit the limit (null = never). Finished sizes are
// appended to results.json and skipped on restart; src/core/endlessTimes.ts is rewritten after every size.
// Run it under `systemd-inhibit --what=sleep:idle` and watch `sensors`; restart with fewer jobs if it gets hot.
import { fork } from 'node:child_process'
import { appendFileSync, existsSync, readFileSync, writeFileSync } from 'node:fs'
import { makeEndless } from '../src/core/generator'

const SEEDS = 7, LIMIT_MS = 30_000, NEVER_AT = 4

if (process.argv[2] === '--one') {
  // child: wait for "go" so the parent's 30 s timer excludes tsx start-up
  const [cols, rows, maxH, seed] = process.argv.slice(3).map(Number)
  process.on('message', () => {
    const t = performance.now()
    makeEndless({ cols, rows, maxH }, seed)
    process.send!(performance.now() - t, () => process.exit(0))
  })
  process.send!('ready')
} else {
  const jobs = +(process.argv[2] ?? 3), out = process.argv[3] ?? '.superpowers/sdd/2026-11-28-endless-slopes/endless-times.jsonl'
  const done = new Map<string, number | null>()
  if (existsSync(out)) for (const line of readFileSync(out, 'utf8').split('\n').filter(Boolean)) { const r = JSON.parse(line); done.set(r.key, r.ms) }
  const sizes: [number, number, number][] = []
  for (let c = 2; c <= 6; c++) for (let r = c; r <= 6; r++) for (let h = 1; h <= 6; h++) sizes.push([c, r, h])
  sizes.sort((a, b) => a[0] * a[1] * a[2] - b[0] * b[1] * b[2])
  const todo = sizes.filter(s => !done.has(s.join('x'))), t0 = Date.now()

  // ms, or Infinity when the seed hit the limit
  const one = (s: number[], seed: number) => new Promise<number>(resolve => {
    const child = fork(process.argv[1], ['--one', ...s.map(String), String(seed)])
    let timer: NodeJS.Timeout | undefined
    child.on('message', m => {
      if (m === 'ready') { timer = setTimeout(() => { child.kill('SIGKILL'); resolve(Infinity) }, LIMIT_MS); child.send('go') }
      else { clearTimeout(timer); resolve(m as number) }
    })
  })

  const writeTable = () => {
    const rows = sizes.filter(s => done.has(s.join('x'))).map(s => { const v = done.get(s.join('x')); return `  '${s.join('x')}': ${v == null ? 'null' : Math.round(v)},` })
    writeFileSync('src/core/endlessTimes.ts', `// Generated by scripts/time-endless.ts on ${new Date().toISOString().slice(0, 10)}, Ryzen 5 5600H laptop, ${jobs} jobs at once.
// PC median ms of makeEndless over seeds 1..${SEEDS}, each seed killed after ${LIMIT_MS / 1000} s; null = never
// (at least ${NEVER_AT} of ${SEEDS} seeds hit the limit). Keys are cols x rows x maxH with cols ≤ rows (the other way round takes the same time).
export const ENDLESS_MEDIAN_MS: Record<string, number | null> = {
${rows.join('\n')}
}
`)
  }

  const worker = async () => {
    for (let s; (s = todo.shift());) {
      const key = s.join('x'), times: number[] = [], st = Date.now()
      for (let seed = 1; seed <= SEEDS && times.filter(t => t === Infinity).length < NEVER_AT; seed++) times.push(await one(s, seed))
      const hits = times.filter(t => t === Infinity).length, ms = hits >= NEVER_AT ? null : [...times].sort((a, b) => a - b)[SEEDS >> 1]
      done.set(key, ms)
      appendFileSync(out, JSON.stringify({ key, ms, times: times.map(t => (t === Infinity ? null : Math.round(t))) }) + '\n')
      writeTable()
      console.log(`${key} ${ms == null ? 'never' : Math.round(ms) + ' ms'} hits ${hits}/${times.length} took ${((Date.now() - st) / 1000).toFixed(0)}s | ${done.size}/${sizes.length} done, ${todo.length} left, ${((Date.now() - t0) / 60000).toFixed(1)} min`)
    }
  }
  console.log(`${todo.length} sizes to time, ${done.size} already done, ${jobs} jobs`)
  await Promise.all(Array.from({ length: jobs }, worker))
  writeTable()
}
